export async function writeQueriesFile(): Promise<void> {
  const queries = generate100BenchmarkQueries();
  const currentDir = dirname(fileURLToPath(import.meta.url));
  const jsonPath = resolve(currentDir, "queries.json");
  const jsonlPath = resolve(currentDir, "queries.jsonl");

  await mkdir(currentDir, { recursive: true });
  await writeFile(jsonPath, JSON.stringify(queries, null, 2), "utf-8");

  const jsonlContent = queries.map((q) => JSON.stringify(q)).join("\n");
  await writeFile(jsonlPath, jsonlContent, "utf-8");

  Logger.info(`Successfully generated and saved 100 benchmark queries to ${jsonPath} and ${jsonlPath}.`);
}


// Run directly if invoked from CLI
if (process.argv[1] && process.argv[1].endsWith("generate_queries.ts")) {
  writeQueriesFile()
    .then(() => {
      console.error("100 Eval Queries generated successfully.");
      process.exit(0);
    })
    .catch((err) => {
      console.error("Failed to generate queries:", err);
      process.exit(1);
    });
}
